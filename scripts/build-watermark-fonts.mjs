/**
 * Self-hosts the watermark tool's text fonts.
 *
 * The watermark tool used to inject a `<link>` to fonts.googleapis.com and then await
 * `document.fonts.load(...)` before drawing to the canvas. Google is unreachable from
 * mainland China, so that await did not fail fast — it sat on a blocked connection until
 * the socket timed out, which is why the tool appeared to freeze on open with no error.
 *
 * This downloads the same families at build time and writes a stylesheet pointing at
 * local copies. The @font-face rules stay lazy: the browser fetches a woff2 only when a
 * family is actually rendered, so picking one font costs one ~20 KB request to our own
 * origin instead of a cross-origin round trip for all ten.
 *
 * Run after changing src/lib/fonts/watermark-fonts.json:
 *     npm run fonts:build
 * Output is committed so deploys never talk to Google. Requires network access.
 */
import { mkdirSync, readFileSync, writeFileSync, readdirSync, rmSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const FAMILIES = JSON.parse(
  readFileSync(join(ROOT, 'src', 'lib', 'fonts', 'watermark-fonts.json'), 'utf8')
);
const OUT_DIR = join(ROOT, 'public', 'fonts', 'watermark');
const OUT_CSS = join(ROOT, 'public', 'fonts', 'watermark.css');

// Google serves woff2 only to a UA it recognises as a modern browser; without a `Chrome/`
// token it falls back to single-weight static TTFs, which are several times larger.
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 ' +
  '(KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36';

// Watermark text is latin — none of these families ship CJK glyphs, and canvas falls back
// to a system font for anything they don't cover. Fetching only these two subsets keeps
// each file around 20 KB instead of pulling in cyrillic, greek and vietnamese.
const SUBSETS = new Set(['latin', 'latin-ext']);

const slug = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, '-');

async function fetchText(url) {
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  return res.text();
}

/**
 * Splits a css2 response into its @font-face blocks, keeping the `/* subset *\/` comment
 * that precedes each one — that comment is the only place the subset name appears.
 */
function parseFaces(css) {
  const faces = [];
  const re = /\/\*\s*([a-z-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g;
  for (const [, subset, block] of css.matchAll(re)) {
    const weight = block.match(/font-weight:\s*(\d+)/)?.[1];
    const url = block.match(/url\((https:\/\/[^)]+\.woff2)\)/)?.[1];
    const range = block.match(/unicode-range:\s*([^;]+);/)?.[1];
    if (weight && url && range) faces.push({ subset, weight: Number(weight), url, range });
  }
  return faces;
}

async function main() {
  mkdirSync(OUT_DIR, { recursive: true });
  const written = new Set();
  const rules = [];
  let bytes = 0;

  for (const { css: family, weights } of FAMILIES) {
    const url =
      'https://fonts.googleapis.com/css2?family=' +
      family.replace(/ /g, '+') +
      `:wght@${weights.join(';')}&display=swap`;

    const faces = parseFaces(await fetchText(url)).filter(
      (f) => SUBSETS.has(f.subset) && weights.includes(f.weight)
    );

    for (const w of weights) {
      if (!faces.some((f) => f.weight === w)) {
        throw new Error(`Google returned no latin woff2 for ${family} ${w}. URL: ${url}`);
      }
    }

    for (const face of faces) {
      const name = `${slug(family)}-${face.weight}-${face.subset}.woff2`;
      const res = await fetch(face.url, { headers: { 'User-Agent': UA } });
      if (!res.ok) throw new Error(`${res.status} downloading ${face.url}`);
      const buf = Buffer.from(await res.arrayBuffer());
      writeFileSync(join(OUT_DIR, name), buf);
      written.add(name);
      bytes += buf.length;

      rules.push(
        `/* ${face.subset} */\n@font-face {\n` +
          `  font-family: '${family}';\n` +
          `  font-style: normal;\n` +
          `  font-weight: ${face.weight};\n` +
          `  font-display: swap;\n` +
          `  src: url('/fonts/watermark/${name}') format('woff2');\n` +
          `  unicode-range: ${face.range};\n}`
      );
    }
  }

  // Drop files left behind by a family that was removed from the JSON, so the directory
  // can't accumulate fonts nothing references.
  for (const f of readdirSync(OUT_DIR)) {
    if (!written.has(f)) rmSync(join(OUT_DIR, f));
  }

  const header =
    '/*\n * Generated by scripts/build-watermark-fonts.mjs — do not edit.\n' +
    ' * Self-hosted because fonts.googleapis.com is unreachable from mainland China.\n' +
    ' * Regenerate with `npm run fonts:build`.\n */\n';
  writeFileSync(OUT_CSS, header + rules.join('\n\n') + '\n');

  console.log(
    `✓ watermark fonts: ${written.size} files, ${(bytes / 1024).toFixed(1)} KB total ` +
      `across ${FAMILIES.length} families → public/fonts/watermark/`
  );
}

if (!existsSync(join(ROOT, 'src', 'lib', 'fonts', 'watermark-fonts.json'))) {
  throw new Error('src/lib/fonts/watermark-fonts.json is missing');
}
await main();
